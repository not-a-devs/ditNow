#!/usr/bin/env bash
# Issue a TLS server certificate for MariaDB from a private team CA and enable it.
#   - CA (created once, reused):  tls/ca.pem (public, distribute to clients) + secrets/tls/ca-key.pem (600, never share)
#   - Server cert (new each run): tls/server-cert.pem, tls/server-key.pem (owned by the container's mysql user)
#   - conf/tls.cnf points MariaDB at these files. Apply with: docker compose up -d
# Names clients connect with go in DB_TLS_SANS (.env), e.g. "DNS:localhost,IP:127.0.0.1,IP:<tailscale-ip>,DNS:<magicdns>".
source "$(dirname "$0")/_common.sh"; load_env
SANS="${DB_TLS_SANS:?set DB_TLS_SANS in .env (e.g. DNS:localhost,IP:127.0.0.1,IP:<tailscale-ip>)}"
CA_DAYS="${DB_TLS_CA_DAYS:-3650}"; CERT_DAYS="${DB_TLS_CERT_DAYS:-825}"
umask 077
# docker creates a missing bind-mount dir as root; take it back so we can write certificates
if [ -d tls ] && [ ! -w tls ]; then
  "${DOCKER[@]}" run --rm -v "$ROOT/tls:/t" --entrypoint chown "${DB_IMAGE:-mariadb:11.4}" "$(id -u):$(id -g)" /t
fi
mkdir -p tls secrets/tls && chmod 700 secrets secrets/tls && chmod 755 tls

if [ ! -f secrets/tls/ca-key.pem ]; then
  openssl ecparam -name prime256v1 -genkey -noout -out secrets/tls/ca-key.pem
  openssl req -x509 -new -sha256 -days "$CA_DAYS" -key secrets/tls/ca-key.pem -out tls/ca.pem \
    -subj "/O=DIT NOW/CN=DIT NOW MariaDB CA" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" -addext "keyUsage=critical,keyCertSign,cRLSign"
  echo "created CA: tls/ca.pem (distribute) / secrets/tls/ca-key.pem (keep secret)"
else
  echo "reusing existing CA: tls/ca.pem"
fi

work=$(mktemp -d -p secrets/tls); trap 'rm -rf "$work"' EXIT
openssl ecparam -name prime256v1 -genkey -noout -out "$work/server-key.pem"
openssl req -new -sha256 -key "$work/server-key.pem" -subj "/O=DIT NOW/CN=ditnow-db" -out "$work/server.csr"
printf 'basicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\nsubjectAltName=%s\n' "$SANS" > "$work/ext.cnf"
openssl x509 -req -sha256 -days "$CERT_DAYS" -in "$work/server.csr" -CA tls/ca.pem -CAkey secrets/tls/ca-key.pem \
  -CAcreateserial -CAserial secrets/tls/ca.srl -extfile "$work/ext.cnf" -out "$work/server-cert.pem" 2>/dev/null
openssl verify -CAfile tls/ca.pem "$work/server-cert.pem" >/dev/null

# Replace server files; the key must be readable only by the container's mysql user (uid 999).
"${DOCKER[@]}" run --rm -v "$ROOT/tls:/t" -v "$ROOT/$work:/w:ro" --entrypoint sh "${DB_IMAGE:-mariadb:11.4}" -c \
  'install -m 644 /w/server-cert.pem /t/server-cert.pem && install -o 999 -g 999 -m 600 /w/server-key.pem /t/server-key.pem'
chmod 644 tls/ca.pem

umask 022
cat > conf/tls.cnf <<'CNF'
# Generated by scripts/gen-tls.sh — server-specific, not committed.
[mariadb]
ssl_ca   = /etc/mysql/tls/ca.pem
ssl_cert = /etc/mysql/tls/server-cert.pem
ssl_key  = /etc/mysql/tls/server-key.pem
tls_version = TLSv1.2,TLSv1.3
# require_secure_transport = ON   # enable once every client connects with TLS
CNF
openssl x509 -in tls/server-cert.pem -noout -subject -enddate -ext subjectAltName | sed 's/^/  /'
echo "done. apply with: docker compose up -d   (clients need tls/ca.pem)"
